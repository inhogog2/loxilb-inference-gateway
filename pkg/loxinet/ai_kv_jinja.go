// kvJjUndef is the Jinja Undefined value: falsy, renders as "", equals
// only another Undefined, iterates as empty, and raises on stricter use
// (attribute/subscript access, +, ordering, method calls).
type kvJjUndef struct{ name string }

// kvJjNS is a namespace() object: the one mutable-by-reference value in the
// subset (Jinja for-loop scopes are per-iteration, so templates thread
// cross-iteration state through namespace attributes).
type kvJjNS struct{ attrs map[string]any }

// kvJjBound is a Python bound method reached as a value (d.items without a
// call). It is callable and truthy; printing it is refused.
type kvJjBound struct {
	obj  any
	name string
}

// kvJinjaTemplate is a compiled template. Compilation is pure; Render may be
// called concurrently.
type kvJinjaTemplate struct {
	nodes []kvJjNode
	// names is every variable name the template reads — the render context
	// it can observe (e.g. whether it consults strftime_now).
	names map[string]bool
	// iteratesContent: some for loop iterates a content value (see
	// kvJjIsContentAccess).
	iteratesContent bool
}

// References reports whether the template reads the named variable.
func (t *kvJinjaTemplate) References(name string) bool { return t.names[name] }

// IteratesContent reports a for loop over x.content, x['content'] or a
// variable named content, through filters, tests and slices, on any base.
// vLLM v0.28.0 (renderers/hf.py _detect_content_format) and SGLang v0.5.18
// (detect_jinja_template_content_format) switch a template to the "openai"
// content format on a subset of these loops — they require the base to be
// a message loop variable — so this is a superset of both.
func (t *kvJinjaTemplate) IteratesContent() bool { return t.iteratesContent }

type kvJjError struct {
	pos int
	msg string
}

func (e *kvJjError) Error() string {
	return fmt.Sprintf("jinja: offset %d: %s", e.pos, e.msg)
}

func kvJjErrf(pos int, format string, a ...any) error {
	return &kvJjError{pos: pos, msg: fmt.Sprintf(format, a...)}
}

// kvJjAt positions a builtin's error at the expression that raised it.
func kvJjAt(pos int, err error) error {
	if err == nil {
		return nil
	}
	var je *kvJjError
	var re *kvJjRaised
	if errors.As(err, &je) || errors.As(err, &re) || errors.Is(err, kvJjBreakSig) || errors.Is(err, kvJjContinueSig) {
		return err
	}
	return &kvJjError{pos: pos, msg: err.Error()}
}

// ---------------------------------------------------------------------------
// Segment lexer: split source into text and {% %} / {{ }} / {# #} tags, then
// apply the whitespace-control rules the engine environment uses.

type kvJjSegKind int

const (
	kvJjSegText kvJjSegKind = iota
	kvJjSegBlock
	kvJjSegOutput
	kvJjSegComment
)

type kvJjSeg struct {
	kind      kvJjSegKind
	body      string // tag interior (trim markers removed) or raw text
	pos       int
	trimLeft  bool
	trimRight bool
	noLstrip  bool // {%+ disables lstrip_blocks for this tag
}

func kvJjLex(src string) ([]kvJjSeg, error) {
	// keep_trailing_newline=False: exactly one trailing newline is dropped
	// before any other processing.
	src = strings.TrimSuffix(src, "\n")

	var segs []kvJjSeg
	i := 0
	for i < len(src) {
		open := strings.IndexByte(src[i:], '{')
		for open >= 0 {
			j := i + open
			if j+1 < len(src) && (src[j+1] == '%' || src[j+1] == '{' || src[j+1] == '#') {
				break
			}
			open = strings.IndexByte(src[i+open+1:], '{')
			if open >= 0 {
				open += j - i + 1
			}
		}
		if open < 0 {
			segs = append(segs, kvJjSeg{kind: kvJjSegText, body: src[i:], pos: i})
			break
		}
		start := i + open
		if start > i {
			segs = append(segs, kvJjSeg{kind: kvJjSegText, body: src[i:start], pos: i})
		}
		var kind kvJjSegKind
		var closer string
		switch src[start+1] {
		case '%':
			kind, closer = kvJjSegBlock, "%}"
		case '{':
			kind, closer = kvJjSegOutput, "}}"
		case '#':
			kind, closer = kvJjSegComment, "#}"
		}
		end, err := kvJjFindClose(src, start+2, closer, kind != kvJjSegComment)
		if err != nil {
			return nil, err
		}
		body := src[start+2 : end]
		seg := kvJjSeg{kind: kind, pos: start}
		if strings.HasPrefix(body, "-") {
			seg.trimLeft = true
			body = body[1:]
		} else if kind == kvJjSegBlock && strings.HasPrefix(body, "+") {
			seg.noLstrip = true
			body = body[1:]
		}
		if strings.HasSuffix(body, "-") {
			seg.trimRight = true
			body = body[:len(body)-1]
		}
		seg.body = strings.TrimSpace(body)
		segs = append(segs, seg)
		i = end + 2
	}

	// Whitespace control, in the engine environment's order: explicit -
	// markers strip all adjacent whitespace; otherwise lstrip_blocks removes
	// a line-leading indent before a block/comment tag and trim_blocks
	// removes the single newline after one. Output tags get neither default.
	for k := range segs {
		if segs[k].kind != kvJjSegText {
			continue
		}
		// Whether the trailing blank run starts a line is a property of the
		// source text, decided before trim_blocks eats the newline that
		// precedes it.
		orig := segs[k].body
		run := len(orig)
		for run > 0 && (orig[run-1] == ' ' || orig[run-1] == '\t') {
			run--
		}
		runAtLineStart := run < len(orig) && (run == 0 && segs[k].pos == 0 || run > 0 && orig[run-1] == '\n')
		if k > 0 {
			prev := &segs[k-1]
			if prev.trimRight {
				segs[k].body = strings.TrimLeft(segs[k].body, " \t\r\n")
			} else if prev.kind == kvJjSegBlock || prev.kind == kvJjSegComment {
				segs[k].body = strings.TrimPrefix(segs[k].body, "\n")
			}
		}
		if k+1 < len(segs) {
			next := &segs[k+1]
			if next.trimLeft {
				segs[k].body = strings.TrimRight(segs[k].body, " \t\r\n")
			} else if (next.kind == kvJjSegBlock || next.kind == kvJjSegComment) && !next.noLstrip && runAtLineStart {
				// Strip only a run that starts at a line start (or template
				// start) — mid-line whitespace before a tag is content. The
				// left-side trims above never reach into a run that has a
				// newline before it; a run that was the whole segment is
				// already gone or is removed here.
				t := segs[k].body
				segs[k].body = strings.TrimRight(t, " \t")
			}
		}
	}
	return segs, nil
}

// kvJjFindClose finds the tag closer. Inside {% %} and {{ }} quoted strings
// are skipped (template string literals may contain braces and newlines);
// comment text is opaque, so apostrophes there are plain characters.
func kvJjFindClose(src string, from int, closer string, skipStrings bool) (int, error) {
	for i := from; i < len(src)-1; i++ {
		c := src[i]
		if skipStrings && (c == '\'' || c == '"') {
			q := c
			i++
			for i < len(src) {
				if src[i] == '\\' {
					i += 2
					continue
				}
				if src[i] == q {
					break
				}
				i++
			}
			if i >= len(src) {
				return 0, kvJjErrf(from, "unterminated string literal")
			}
			continue
		}
		if c == closer[0] && src[i+1] == closer[1] {
			// A '-' right-trim marker sits between body and closer.
			return i, nil
		}
	}
	return 0, kvJjErrf(from, "unterminated tag (missing %s)", closer)
}

// ---------------------------------------------------------------------------
// Statement nodes.

type kvJjNode interface {
	exec(rt *kvJjRT, sb *strings.Builder) error
}

type kvJjText struct{ s string }

type kvJjOutput struct {
	e   kvJjExpr
	pos int
}

type kvJjIf struct {
	conds  []kvJjExpr // one per if/elif branch
	bodies [][]kvJjNode
	els    []kvJjNode
}

type kvJjFor struct {
	targets []string // one name, or a tuple unpack
	seq     kvJjExpr
	filter  kvJjExpr // inline `if` filter, nil when absent
	body    []kvJjNode
	els     []kvJjNode
	pos     int
}

type kvJjSet struct {
	targets []string // one name, or a tuple unpack
	attr    string   // namespace attribute assignment (single target)
	e       kvJjExpr
	pos     int
}

type kvJjSetBlock struct {
	name string
	body []kvJjNode
}

type kvJjMacroDecl struct {
	name     string
	params   []string
	defaults []kvJjExpr // parallel to params; nil = no default
	body     []kvJjNode
	pos      int
}

// kvJjMacro is a defined macro: calling it renders its body to a string.
type kvJjMacro struct{ decl *kvJjMacroDecl }

type kvJjMacroDef struct{ decl *kvJjMacroDecl }

type kvJjLoopCtl struct{ brk bool }

var (
	kvJjBreakSig    = errors.New("jinja: break")
	kvJjContinueSig = errors.New("jinja: continue")
)

// kvJinjaCompile parses template source into an executable node tree.
func kvJinjaCompile(src string) (*kvJinjaTemplate, error) {
	segs, err := kvJjLex(src)
	if err != nil {
		return nil, err
	}
	p := &kvJjSegParser{segs: segs, names: map[string]bool{}}
	nodes, err := p.parseBody(nil)
	if err != nil {
		return nil, err
	}
	// varargs/kwargs/caller are implicit macro locals the executor does not
	// model; a template reading them must refuse rather than see Undefined.
	for _, n := range []string{"varargs", "kwargs", "caller"} {
		if p.names[n] {
			return nil, kvJjErrf(0, "unsupported implicit macro variable %q", n)
		}
	}
	return &kvJinjaTemplate{nodes: nodes, names: p.names, iteratesContent: p.iteratesContent}, nil
}

type kvJjSegParser struct {
	segs            []kvJjSeg
	i               int
	loopDepth       int
	names           map[string]bool
	iteratesContent bool
}

// kvJjIsContentAccess reports an expression that reads a content value:
// x.content, x['content'] or the variable content, under any filters,
// tests and slices.
func kvJjIsContentAccess(e kvJjExpr) bool {
	for {
		switch x := e.(type) {
		case *kvJjFilter:
			e = x.e
		case *kvJjTest:
			e = x.e
		case *kvJjSlice:
			e = x.obj
		case *kvJjAttr:
			return x.name == "content"
		case *kvJjIndex:
			lit, ok := x.idx.(*kvJjLit)
			return ok && lit.v == "content"
		case *kvJjVar:
			return x.name == "content"
		default:
			return false
		}
	}
}

// parseBody parses statements until one of the terminator keywords appears,
// which is left un-consumed for the caller.
func (p *kvJjSegParser) parseBody(until []string) ([]kvJjNode, error) {
	var nodes []kvJjNode
	for p.i < len(p.segs) {
		seg := p.segs[p.i]
		switch seg.kind {
		case kvJjSegText:
			p.i++
			if seg.body != "" {
				nodes = append(nodes, &kvJjText{s: seg.body})
			}
		case kvJjSegComment:
			p.i++
		case kvJjSegOutput:
			p.i++
			ep, err := p.exprParser(seg.body, seg.pos)
			if err != nil {
				return nil, err
			}
			e, err := ep.parseTuple(true, false)
			if err == nil {
				err = ep.expectEnd()
			}
			if err != nil {
				return nil, err
			}
			nodes = append(nodes, &kvJjOutput{e: e, pos: seg.pos})
		case kvJjSegBlock:
			kw, _ := kvJjSplitKw(seg.body)
			for _, u := range until {
				if kw == u {
					return nodes, nil
				}
			}
			n, err := p.parseBlock(seg)
			if err != nil {
				return nil, err
			}
			nodes = append(nodes, n)
		}
	}
	if len(until) != 0 {
		return nil, kvJjErrf(0, "unexpected end of template (missing %s)", until[len(until)-1])
	}
	return nodes, nil
}

func kvJjSplitKw(body string) (string, string) {
	if sp := strings.IndexAny(body, " \t\r\n"); sp >= 0 {
		return body[:sp], strings.TrimSpace(body[sp:])
	}
	return body, ""
}

func (p *kvJjSegParser) exprParser(src string, pos int) (*kvJjExprParser, error) {
	toks, err := kvJjLexExpr(src, pos)
	if err != nil {
		return nil, err
	}
	return &kvJjExprParser{toks: toks, names: p.names}, nil
}

func (p *kvJjSegParser) parseBlock(seg kvJjSeg) (kvJjNode, error) {
	kw, rest := kvJjSplitKw(seg.body)
	p.i++
	switch kw {
	case "if":
		return p.parseIf(rest, seg.pos)
	case "for":
		return p.parseFor(rest, seg.pos)
	case "set":
		return p.parseSet(rest, seg.pos)
	case "macro":
		return p.parseMacro(rest, seg.pos)
	case "continue", "break":
		if rest != "" {
			return nil, kvJjErrf(seg.pos, "%s takes no arguments", kw)
		}
		if p.loopDepth == 0 {
			return nil, kvJjErrf(seg.pos, "%s outside of a loop", kw)
		}
		return &kvJjLoopCtl{brk: kw == "break"}, nil
	}
	return nil, kvJjErrf(seg.pos, "unsupported block %q", kw)
}

// expectTerm consumes the terminator tag parseBody stopped at and returns
// its keyword and remainder.
func (p *kvJjSegParser) expectTerm() (string, string, int) {
	term := p.segs[p.i]
	p.i++
	kw, rest := kvJjSplitKw(term.body)
	return kw, rest, term.pos
}

func (p *kvJjSegParser) parseIf(condSrc string, pos int) (kvJjNode, error) {
	n := &kvJjIf{}
	for {
		ep, err := p.exprParser(condSrc, pos)
		if err != nil {
			return nil, err
		}
		cond, err := ep.parseTuple(true, false)
		if err == nil {
			err = ep.expectEnd()
		}
		if err != nil {
			return nil, err
		}
		body, err := p.parseBody([]string{"elif", "else", "endif"})
		if err != nil {
			return nil, err
		}
		n.conds = append(n.conds, cond)
		n.bodies = append(n.bodies, body)
		kw, rest, tpos := p.expectTerm()
		switch kw {
		case "endif":
			return n, nil
		case "elif":
			condSrc, pos = rest, tpos
		case "else":
			els, err := p.parseBody([]string{"endif"})
			if err != nil {
				return nil, err
			}
			n.els = els
			p.i++ // consume endif
			return n, nil
		}
	}
}

// parseTargets parses an assignment target list: name (, name)*.
func (ep *kvJjExprParser) parseTargets() ([]string, error) {
	var names []string
	for {
		t := ep.next()
		if t.kind != "ident" || kvJjReserved[t.s] {
			return nil, kvJjErrf(t.pos, "unsupported assignment target %q", t.s)
		}
		names = append(names, t.s)
		if !ep.accept("op", ",") {
			return names, nil
		}
	}
}

func (p *kvJjSegParser) parseFor(head string, pos int) (kvJjNode, error) {
	ep, err := p.exprParser(head, pos)
	if err != nil {
		return nil, err
	}
	targets, err := ep.parseTargets()
	if err != nil {
		return nil, err
	}
	if !ep.accept("ident", "in") {
		return nil, kvJjErrf(pos, "for: expected \"<target> in <expr>\"")
	}
	seq, err := ep.parseTuple(false, false)
	if err != nil {
		return nil, err
	}
	n := &kvJjFor{targets: targets, seq: seq, pos: pos}
	if kvJjIsContentAccess(seq) {
		p.iteratesContent = true
	}
	if ep.accept("ident", "if") {
		if n.filter, err = ep.parseExpression(true); err != nil {
			return nil, err
		}
	}
	if ep.cur().kind == "ident" && ep.cur().s == "recursive" {
		return nil, kvJjErrf(pos, "for: recursive loops are unsupported")
	}
	if err := ep.expectEnd(); err != nil {
		return nil, err
	}
	p.loopDepth++
	n.body, err = p.parseBody([]string{"else", "endfor"})
	p.loopDepth--
	if err != nil {
		return nil, err
	}
	if kw, _, _ := p.expectTerm(); kw == "else" {
		// The else body runs outside the loop: continue/break there is an
		// error in Jinja too.
		saved := p.loopDepth
		p.loopDepth = 0
		n.els, err = p.parseBody([]string{"endfor"})
		p.loopDepth = saved
		if err != nil {
			return nil, err
		}
		p.i++ // consume endfor
	}
	return n, nil
}

func (p *kvJjSegParser) parseSet(src string, pos int) (kvJjNode, error) {
	ep, err := p.exprParser(src, pos)
	if err != nil {
		return nil, err
	}
	first := ep.cur()
	if first.kind == "ident" && ep.toks[ep.i+1].kind == "op" && ep.toks[ep.i+1].s == "." {
		// Namespace attribute: ns.attr = expr
		ep.i += 2
		attr := ep.next()
		if attr.kind != "ident" {
			return nil, kvJjErrf(pos, "set: unsupported target")
		}
		if !ep.accept("op", "=") {
			return nil, kvJjErrf(pos, "set: expected \"=\"")
		}
		p.names[first.s] = true
		e, err := ep.parseTuple(true, false)
		if err == nil {
			err = ep.expectEnd()
		}
		if err != nil {
			return nil, err
		}
		return &kvJjSet{targets: []string{first.s}, attr: attr.s, e: e, pos: pos}, nil
	}
	targets, err := ep.parseTargets()
	if err != nil {
		return nil, err
	}
	if ep.cur().kind == "end" {
		// Block set: {% set x %}...{% endset %}
		if len(targets) != 1 {
			return nil, kvJjErrf(pos, "set: block assignment needs one name")
		}
		body, err := p.parseBody([]string{"endset"})
		if err != nil {
			return nil, err
		}
		p.i++ // consume endset
		return &kvJjSetBlock{name: targets[0], body: body}, nil
	}
	if !ep.accept("op", "=") {
		return nil, kvJjErrf(pos, "set: expected \"<target> = <expr>\"")
	}
	e, err := ep.parseTuple(true, false)
	if err == nil {
		err = ep.expectEnd()
	}
	if err != nil {
		return nil, err
	}
	return &kvJjSet{targets: targets, e: e, pos: pos}, nil
}

func (p *kvJjSegParser) parseMacro(src string, pos int) (kvJjNode, error) {
	ep, err := p.exprParser(src, pos)
	if err != nil {
		return nil, err
	}
	name := ep.next()
	if name.kind != "ident" || kvJjReserved[name.s] {
		return nil, kvJjErrf(pos, "macro: expected a name")
	}
	d := &kvJjMacroDecl{name: name.s, pos: pos}
	if !ep.accept("op", "(") {
		return nil, kvJjErrf(pos, "macro: expected a parameter list")
	}
	for !ep.accept("op", ")") {
		if len(d.params) > 0 && !ep.accept("op", ",") {
			return nil, kvJjErrf(ep.cur().pos, "macro: expected \",\"")
		}
		if ep.accept("op", ")") {
			break
		}
		pn := ep.next()
		if pn.kind != "ident" || kvJjReserved[pn.s] {
			return nil, kvJjErrf(pn.pos, "macro: bad parameter")
		}
		var def kvJjExpr
		if ep.accept("op", "=") {
			if def, err = ep.parseExpression(true); err != nil {
				return nil, err
			}
		} else if len(d.defaults) > 0 && d.defaults[len(d.defaults)-1] != nil {
			return nil, kvJjErrf(pn.pos, "macro: non-default parameter after a default one")
		}
		d.params = append(d.params, pn.s)
		d.defaults = append(d.defaults, def)
	}
	if err := ep.expectEnd(); err != nil {
		return nil, err
	}
	saved := p.loopDepth
	p.loopDepth = 0
	d.body, err = p.parseBody([]string{"endmacro"})
	p.loopDepth = saved
	if err != nil {
		return nil, err
	}
	p.i++ // consume endmacro
	return &kvJjMacroDef{decl: d}, nil
}

// ---------------------------------------------------------------------------
// Expression lexer + parser, following Jinja's grammar:
//   tuple      := expr (',' expr)* [',']
//   expression := or ['if' or ['else' expression]]
//   or/and/not, compare (== != < <= > >= in, not in),
//   math1 (+ -) < concat (~) < math2 (* / // %) < pow < unary,
//   unary := ('-' unary | primary postfix*) filter_expr*
// Filters, tests and calls bind at the unary level, so `-l|length` is
// `(-l)|length` and `a ~ b|trim` is `a ~ (b|trim)`.

type kvJjTok struct {
	kind string // ident, int, str, op, end
	s    string
	n    int
	pos  int
}

// kvJjReserved are keywords that can never be a variable name.
var kvJjReserved = map[string]bool{
	"and": true, "or": true, "not": true, "in": true, "is": true, "if": true, "else": true,
	"true": true, "false": true, "none": true, "True": true, "False": true, "None": true,
}

func kvJjLexExpr(src string, base int) ([]kvJjTok, error) {
	var toks []kvJjTok
	i := 0
	for i < len(src) {
		c := src[i]
		switch {
		case c == ' ' || c == '\t' || c == '\r' || c == '\n':
			i++
		case c == '\'' || c == '"':
			s, n, err := kvJjLexString(src[i:], base+i)
			if err != nil {
				return nil, err
			}
			toks = append(toks, kvJjTok{kind: "str", s: s, pos: base + i})
			i += n
		case c >= '0' && c <= '9':
			j := i
			for j < len(src) && (src[j] >= '0' && src[j] <= '9' || src[j] == '_') {
				j++
			}
			if j < len(src) && (src[j] == '.' && j+1 < len(src) && src[j+1] >= '0' && src[j+1] <= '9' || src[j] == 'e' || src[j] == 'E') {
				return nil, kvJjErrf(base+i, "float literals are unsupported")
			}
			n, err := strconv.Atoi(strings.ReplaceAll(src[i:j], "_", ""))
			if err != nil {
				return nil, kvJjErrf(base+i, "bad integer literal %q", src[i:j])
			}
			toks = append(toks, kvJjTok{kind: "int", n: n, pos: base + i})
			i = j
		case c == '_' || c >= 0x80 || unicode.IsLetter(rune(c)):
			j := i
			for j < len(src) {
				r := src[j]
				if r == '_' || r >= 0x80 || unicode.IsLetter(rune(r)) || unicode.IsDigit(rune(r)) {
					j++
					continue
				}
				break
			}
			toks = append(toks, kvJjTok{kind: "ident", s: src[i:j], pos: base + i})
			i = j
		default:
			two := ""
			if i+1 < len(src) {
				two = src[i : i+2]
			}
			switch two {
			case "==", "!=", "<=", ">=", "//", "**":
				toks = append(toks, kvJjTok{kind: "op", s: two, pos: base + i})
				i += 2
				continue
			}
			switch c {
			case '+', '-', '*', '/', '%', '<', '>', '(', ')', '[', ']', '{', '}', '.', ',', ':', '|', '=', '~':
				toks = append(toks, kvJjTok{kind: "op", s: string(c), pos: base + i})
				i++
			default:
				return nil, kvJjErrf(base+i, "unsupported character %q in expression", string(c))
			}
		}
	}
	toks = append(toks, kvJjTok{kind: "end", pos: base + len(src)})
	return toks, nil
}

// kvJjLexString decodes a quoted literal the way Jinja does: the body is
// passed through Python's unicode-escape codec, so \n \t \xNN \uNNNN
// \UNNNNNNNN \N{...} octal and \<newline> are escapes and an unknown escape
// is kept verbatim. Returns the value and the bytes consumed.
func kvJjLexString(src string, pos int) (string, int, error) {
	q := src[0]
	var b strings.Builder
	i := 1
	for i < len(src) {
		c := src[i]
		if c == q {
			return b.String(), i + 1, nil
		}
		if c != '\\' || i+1 >= len(src) {
			b.WriteByte(c)
			i++
			continue
		}
		e := src[i+1]
		i += 2
		switch e {
		case '\n':
		case '\\':
			b.WriteByte('\\')
		case '\'':
			b.WriteByte('\'')
		case '"':
			b.WriteByte('"')
		case 'a':
			b.WriteByte('\a')
		case 'b':
			b.WriteByte('\b')
		case 'f':
			b.WriteByte('\f')
		case 'n':
			b.WriteByte('\n')
		case 'r':
			b.WriteByte('\r')
		case 't':
			b.WriteByte('\t')
		case 'v':
			b.WriteByte('\v')
		case 'x', 'u', 'U':
			width := map[byte]int{'x': 2, 'u': 4, 'U': 8}[e]
			if i+width > len(src) {
				return "", 0, kvJjErrf(pos, "truncated \\%c escape", e)
			}
			v, err := strconv.ParseUint(src[i:i+width], 16, 32)
			if err != nil || v > unicode.MaxRune {
				return "", 0, kvJjErrf(pos, "bad \\%c escape", e)
			}
			b.WriteRune(rune(v))
			i += width
		case '0', '1', '2', '3', '4', '5', '6', '7':
			v := int(e - '0')
			for k := 0; k < 2 && i < len(src) && src[i] >= '0' && src[i] <= '7'; k++ {
				v = v*8 + int(src[i]-'0')
				i++
			}
			b.WriteRune(rune(v))
		case 'N':
			return "", 0, kvJjErrf(pos, "\\N{...} escapes are unsupported")
		default:
			b.WriteByte('\\')
			b.WriteByte(e)
		}
	}
	return "", 0, kvJjErrf(pos, "unterminated string literal")
}

type kvJjExpr interface {
	eval(rt *kvJjRT) (any, error)
}

type kvJjExprParser struct {
	toks  []kvJjTok
	i     int
	names map[string]bool
}

// kvJjParseExprAll parses a complete standalone expression.
func kvJjParseExprAll(src string, base int) (kvJjExpr, error) {
	toks, err := kvJjLexExpr(src, base)
	if err != nil {
		return nil, err
	}
	p := &kvJjExprParser{toks: toks, names: map[string]bool{}}
	e, err := p.parseTuple(true, false)
	if err != nil {
		return nil, err
	}
	return e, p.expectEnd()
}

func (p *kvJjExprParser) cur() kvJjTok  { return p.toks[p.i] }
func (p *kvJjExprParser) peek() kvJjTok { return p.toks[min(p.i+1, len(p.toks)-1)] }
func (p *kvJjExprParser) next() kvJjTok {
	t := p.toks[p.i]
	if t.kind != "end" {
		p.i++
	}
	return t
}

func (p *kvJjExprParser) accept(kind, s string) bool {
	t := p.cur()
	if t.kind == kind && (s == "" || t.s == s) {
		p.i++
		return true
	}
	return false
}

func (p *kvJjExprParser) expectEnd() error {
	if t := p.cur(); t.kind != "end" {
		return kvJjErrf(t.pos, "unexpected %q after expression", t.s)
	}
	return nil
}

func (p *kvJjExprParser) atTupleEnd() bool {
	t := p.cur()
	if t.kind == "end" {
		return true
	}
	if t.kind == "op" && (t.s == ")" || t.s == "]" || t.s == "}" || t.s == "=" || t.s == ":") {
		return true
	}
	return t.kind == "ident" && (t.s == "if" || t.s == "in" || t.s == "else" || t.s == "recursive")
}

// parseTuple parses a possibly comma-separated expression list; a single
// expression without a trailing comma is returned as itself.
func (p *kvJjExprParser) parseTuple(withCondexpr, explicitParens bool) (kvJjExpr, error) {
	var items []kvJjExpr
	isTuple := false
	for {
		if len(items) > 0 {
			if !p.accept("op", ",") {
				break
			}
			isTuple = true
		}
		if p.atTupleEnd() {
			break
		}
		e, err := p.parseExpression(withCondexpr)
		if err != nil {
			return nil, err
		}
		items = append(items, e)
	}
	if !isTuple {
		if len(items) == 0 {
			if explicitParens {
				return &kvJjSeqLit{tuple: true}, nil
			}
			return nil, kvJjErrf(p.cur().pos, "expected an expression")
		}
		return items[0], nil
	}
	return &kvJjSeqLit{items: items, tuple: true}, nil
}

func (p *kvJjExprParser) parseExpression(withCondexpr bool) (kvJjExpr, error) {
	if !withCondexpr {
		return p.parseOr()
	}
	e, err := p.parseOr()
	if err != nil {
		return nil, err
	}
	for p.accept("ident", "if") {
		cond, err := p.parseOr()
		if err != nil {
			return nil, err
		}
		var els kvJjExpr
		if p.accept("ident", "else") {
			if els, err = p.parseExpression(true); err != nil {
				return nil, err
			}
		}
		e = &kvJjCond{cond: cond, a: e, b: els}
	}
	return e, nil
}

func (p *kvJjExprParser) parseOr() (kvJjExpr, error) {
	l, err := p.parseAnd()
	if err != nil {
		return nil, err
	}
	for p.accept("ident", "or") {
		r, err := p.parseAnd()
		if err != nil {
			return nil, err
		}
		l = &kvJjBool{op: "or", l: l, r: r}
	}
	return l, nil
}

func (p *kvJjExprParser) parseAnd() (kvJjExpr, error) {
	l, err := p.parseNot()
	if err != nil {
		return nil, err
	}
	for p.accept("ident", "and") {
		r, err := p.parseNot()
		if err != nil {
			return nil, err
		}
		l = &kvJjBool{op: "and", l: l, r: r}
	}
	return l, nil
}

func (p *kvJjExprParser) parseNot() (kvJjExpr, error) {
	if p.accept("ident", "not") {
		e, err := p.parseNot()
		if err != nil {
			return nil, err
		}
		return &kvJjNot{e: e}, nil
	}
	return p.parseCompare()
}

func (p *kvJjExprParser) parseCompare() (kvJjExpr, error) {
	l, err := p.parseMath1()
	if err != nil {
		return nil, err
	}
	for ops := 0; ; ops++ {
		t := p.cur()
		var op string
		switch {
		case t.kind == "op" && (t.s == "==" || t.s == "!=" || t.s == "<" || t.s == "<=" || t.s == ">" || t.s == ">="):
			op = t.s
			p.i++
		case t.kind == "ident" && t.s == "in":
			op = "in"
			p.i++
		case t.kind == "ident" && t.s == "not" && p.peek().kind == "ident" && p.peek().s == "in":
			op = "notin"
			p.i += 2
		default:
			return l, nil
		}
		if ops > 0 {
			// a < b < c means (a < b) and (b < c) in Jinja; not modelled.
			return nil, kvJjErrf(t.pos, "chained comparisons are unsupported")
		}
		r, err := p.parseMath1()
		if err != nil {
			return nil, err
		}
		l = &kvJjCmp{op: op, l: l, r: r, pos: t.pos}
	}
}

func (p *kvJjExprParser) parseBinary(ops []string, sub func() (kvJjExpr, error)) (kvJjExpr, error) {
	l, err := sub()
	if err != nil {
		return nil, err
	}
	for {
		t := p.cur()
		matched := false
		for _, o := range ops {
			if t.kind == "op" && t.s == o {
				matched = true
			}
		}
		if !matched {
			return l, nil
		}
		p.i++
		r, err := sub()
		if err != nil {
			return nil, err
		}
		l = &kvJjArith{op: t.s, l: l, r: r, pos: t.pos}
	}
}

func (p *kvJjExprParser) parseMath1() (kvJjExpr, error) {
	return p.parseBinary([]string{"+", "-"}, p.parseConcat)
}

func (p *kvJjExprParser) parseConcat() (kvJjExpr, error) {
	return p.parseBinary([]string{"~"}, p.parseMath2)
}

func (p *kvJjExprParser) parseMath2() (kvJjExpr, error) {
	return p.parseBinary([]string{"*", "/", "//", "%"}, p.parsePow)
}

func (p *kvJjExprParser) parsePow() (kvJjExpr, error) {
	e, err := p.parseUnary(true)
	if err != nil {
		return nil, err
	}
	if t := p.cur(); t.kind == "op" && t.s == "**" {
		return nil, kvJjErrf(t.pos, "operator ** is unsupported")
	}
	return e, nil
}

func (p *kvJjExprParser) parseUnary(withFilter bool) (kvJjExpr, error) {
	var e kvJjExpr
	var err error
	t := p.cur()
	switch {
	case t.kind == "op" && t.s == "-":
		p.i++
		inner, err := p.parseUnary(false)
		if err != nil {
			return nil, err
		}
		e = &kvJjNeg{e: inner, pos: t.pos}
	case t.kind == "op" && t.s == "+":
		return nil, kvJjErrf(t.pos, "unary + is unsupported")
	default:
		if e, err = p.parsePrimary(); err != nil {
			return nil, err
		}
	}
	if e, err = p.parsePostfix(e); err != nil {
		return nil, err
	}
	if withFilter {
		return p.parseFilterExpr(e)
	}
	return e, nil
}

func (p *kvJjExprParser) parsePrimary() (kvJjExpr, error) {
	t := p.next()
	switch t.kind {
	case "str":
		s := t.s
		for p.cur().kind == "str" {
			s += p.next().s
		}
		return &kvJjLit{v: s}, nil
	case "int":
		return &kvJjLit{v: t.n}, nil
	case "ident":
		switch t.s {
		case "true", "True":
			return &kvJjLit{v: true}, nil
		case "false", "False":
			return &kvJjLit{v: false}, nil
		case "none", "None":
			return &kvJjLit{v: nil}, nil
		}
		if kvJjReserved[t.s] {
			return nil, kvJjErrf(t.pos, "unexpected keyword %q", t.s)
		}
		p.names[t.s] = true
		return &kvJjVar{name: t.s, pos: t.pos}, nil
	case "op":
		switch t.s {
		case "(":
			e, err := p.parseTuple(true, true)
			if err != nil {
				return nil, err
			}
			if !p.accept("op", ")") {
				return nil, kvJjErrf(t.pos, "missing \")\"")
			}
			return e, nil
		case "[":
			var items []kvJjExpr
			for !p.accept("op", "]") {
				if len(items) > 0 && !p.accept("op", ",") {
					return nil, kvJjErrf(p.cur().pos, "list: expected \",\"")
				}
				if p.accept("op", "]") {
					break
				}
				e, err := p.parseExpression(true)
				if err != nil {
					return nil, err
				}
				items = append(items, e)
			}
			return &kvJjSeqLit{items: items}, nil
		case "{":
			d := &kvJjDictLit{}
			for !p.accept("op", "}") {
				if len(d.keys) > 0 && !p.accept("op", ",") {
					return nil, kvJjErrf(p.cur().pos, "dict: expected \",\"")
				}
				if p.accept("op", "}") {
					break
				}
				k, err := p.parseExpression(true)
				if err != nil {
					return nil, err
				}
				if !p.accept("op", ":") {
					return nil, kvJjErrf(p.cur().pos, "dict: expected \":\"")
				}
				v, err := p.parseExpression(true)
				if err != nil {
					return nil, err
				}
				d.keys = append(d.keys, k)
				d.vals = append(d.vals, v)
			}
			d.pos = t.pos
			return d, nil
		}
	}
	return nil, kvJjErrf(t.pos, "unexpected token %q", t.s)
}

func (p *kvJjExprParser) parsePostfix(e kvJjExpr) (kvJjExpr, error) {
	for {
		t := p.cur()
		switch {
		case t.kind == "op" && t.s == ".":
			p.i++
			name := p.next()
			switch name.kind {
			case "ident":
				e = &kvJjAttr{obj: e, name: name.s, pos: name.pos}
			case "int":
				e = &kvJjIndex{obj: e, idx: &kvJjLit{v: name.n}, pos: name.pos}
			default:
				return nil, kvJjErrf(name.pos, "expected attribute name after \".\"")
			}
		case t.kind == "op" && t.s == "[":
			p.i++
			var err error
			if e, err = p.parseSubscript(e, t.pos); err != nil {
				return nil, err
			}
		case t.kind == "op" && t.s == "(":
			p.i++
			args, err := p.parseCallArgs()
			if err != nil {
				return nil, err
			}
			e = &kvJjCall{fn: e, args: args, pos: t.pos}
		default:
			return e, nil
		}
	}
}

func (p *kvJjExprParser) parseFilterExpr(e kvJjExpr) (kvJjExpr, error) {
	for {
		t := p.cur()
		switch {
		case t.kind == "op" && t.s == "|":
			p.i++
			name := p.next()
			if name.kind != "ident" {
				return nil, kvJjErrf(name.pos, "expected filter name after \"|\"")
			}
			f := &kvJjFilter{e: e, name: name.s, pos: name.pos}
			if _, ok := kvJjFilters[name.s]; !ok {
				// Jinja resolves filters at compile time.
				return nil, kvJjErrf(name.pos, "unsupported filter %q", name.s)
			}
			if p.accept("op", "(") {
				var err error
				if f.args, err = p.parseCallArgs(); err != nil {
					return nil, err
				}
			}
			e = f
		case t.kind == "ident" && t.s == "is":
			p.i++
			negate := p.accept("ident", "not")
			name := p.next()
			if name.kind != "ident" && !(name.kind == "op" && (name.s == "==" || name.s == "!=" || name.s == "<" || name.s == "<=" || name.s == ">" || name.s == ">=")) {
				return nil, kvJjErrf(name.pos, "expected test name after \"is\"")
			}
			te := &kvJjTest{e: e, name: name.s, negate: negate, pos: name.pos}
			c := p.cur()
			if p.accept("op", "(") {
				args, err := p.parseCallArgs()
				if err != nil {
					return nil, err
				}
				if len(args.kw) != 0 {
					return nil, kvJjErrf(name.pos, "keyword arguments to tests are unsupported")
				}
				te.args = args.pos
			} else if c.kind == "str" || c.kind == "int" || (c.kind == "op" && (c.s == "(" || c.s == "[" || c.s == "{")) ||
				(c.kind == "ident" && c.s != "else" && c.s != "or" && c.s != "and" && c.s != "if" && c.s != "is" && c.s != "in" && c.s != "not") {
				arg, err := p.parsePrimary()
				if err != nil {
					return nil, err
				}
				if arg, err = p.parsePostfix(arg); err != nil {
					return nil, err
				}
				te.args = []kvJjExpr{arg}
			}
			e = te
		case t.kind == "op" && t.s == "(":
			p.i++
			args, err := p.parseCallArgs()
			if err != nil {
				return nil, err
			}
			e = &kvJjCall{fn: e, args: args, pos: t.pos}
		default:
			return e, nil
		}
	}
}

type kvJjCallArgs struct {
	pos    []kvJjExpr
	kw     []string
	kwVals []kvJjExpr
}

// parseCallArgs parses "(a, b, k=v)" after the opening parenthesis.
func (p *kvJjExprParser) parseCallArgs() (*kvJjCallArgs, error) {
	a := &kvJjCallArgs{}
	first := true
	for !p.accept("op", ")") {
		if !first && !p.accept("op", ",") {
			return nil, kvJjErrf(p.cur().pos, "expected \",\" or \")\" in argument list")
		}
		first = false
		if p.accept("op", ")") {
			break
		}
		if t := p.cur(); t.kind == "op" && (t.s == "*" || t.s == "**") {
			return nil, kvJjErrf(t.pos, "*args/**kwargs calls are unsupported")
		}
		if t := p.cur(); t.kind == "ident" && p.peek().kind == "op" && p.peek().s == "=" {
			p.i += 2
			v, err := p.parseExpression(true)
			if err != nil {
				return nil, err
			}
			for _, k := range a.kw {
				if k == t.s {
					return nil, kvJjErrf(t.pos, "duplicate keyword argument %q", t.s)
				}
			}
			a.kw = append(a.kw, t.s)
			a.kwVals = append(a.kwVals, v)
			continue
		}
		if len(a.kw) > 0 {
			return nil, kvJjErrf(p.cur().pos, "positional argument after keyword argument")
		}
		v, err := p.parseExpression(true)
		if err != nil {
			return nil, err
		}
		a.pos = append(a.pos, v)
	}
	return a, nil
}

func (p *kvJjExprParser) parseSubscript(obj kvJjExpr, pos int) (kvJjExpr, error) {
	var parts [3]kvJjExpr
	slot := 0
	isSlice := false
	for {
		t := p.cur()
		if t.kind == "op" && t.s == ":" {
			p.i++
			isSlice = true
			slot++
			if slot > 2 {
				return nil, kvJjErrf(t.pos, "too many slice separators")
			}
			continue
		}
		if t.kind == "op" && t.s == "]" {
			p.i++
			break
		}
		if parts[slot] != nil {
			return nil, kvJjErrf(t.pos, "unsupported subscript")
		}
		e, err := p.parseExpression(true)
		if err != nil {
			return nil, err
		}
		parts[slot] = e
	}
	if !isSlice {
		if parts[0] == nil {
			return nil, kvJjErrf(pos, "empty subscript")
		}
		return &kvJjIndex{obj: obj, idx: parts[0], pos: pos}, nil
	}
	return &kvJjSlice{obj: obj, start: parts[0], stop: parts[1], step: parts[2], pos: pos}, nil
}

