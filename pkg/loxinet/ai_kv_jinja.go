// ---------------------------------------------------------------------------
// Runtime.

// kvJjMaxCallDepth bounds macro recursion (Python's own recursion limit is
// what stops a runaway template engine-side; the gateway refuses earlier).
const kvJjMaxCallDepth = 64

type kvJjRT struct {
	scopes []map[string]any
	root   map[string]any // the template's top-level frame, shared by macros
	depth  int
}

func (rt *kvJjRT) lookup(name string) (any, bool) {
	for i := len(rt.scopes) - 1; i >= 0; i-- {
		if v, ok := rt.scopes[i][name]; ok {
			return v, true
		}
	}
	return nil, false
}

// set writes the innermost scope: Jinja assignments never escape a for-loop
// or macro frame (templates use namespace() when they need that), while
// assignments inside {% if %} blocks share the enclosing frame.
func (rt *kvJjRT) set(name string, v any) {
	rt.scopes[len(rt.scopes)-1][name] = v
}

// Render executes the template. ctx values use Go types (string, int, bool,
// nil, []any, map[string]any — keys taken in sorted order) or the executor's
// own value model (*kvJjDict for insertion-ordered dicts, *kvJjBuiltin).
func (t *kvJinjaTemplate) Render(ctx map[string]any) (string, error) {
	vars := make(map[string]any, len(ctx))
	for k, v := range ctx {
		vars[k] = kvJjFromGo(v)
	}
	root := map[string]any{}
	rt := &kvJjRT{scopes: []map[string]any{kvJjGlobals, vars, root}, root: root}
	var sb strings.Builder
	if err := kvJjExecBody(rt, t.nodes, &sb); err != nil {
		return "", err
	}
	return sb.String(), nil
}

func kvJjExecBody(rt *kvJjRT, nodes []kvJjNode, sb *strings.Builder) error {
	for _, n := range nodes {
		if err := n.exec(rt, sb); err != nil {
			return err
		}
	}
	return nil
}

func (n *kvJjText) exec(rt *kvJjRT, sb *strings.Builder) error {
	sb.WriteString(n.s)
	return nil
}

func (n *kvJjOutput) exec(rt *kvJjRT, sb *strings.Builder) error {
	v, err := n.e.eval(rt)
	if err != nil {
		return err
	}
	s, err := kvJjToStr(v)
	if err != nil {
		return kvJjAt(n.pos, err)
	}
	sb.WriteString(s)
	return nil
}

func (n *kvJjIf) exec(rt *kvJjRT, sb *strings.Builder) error {
	for i, cond := range n.conds {
		v, err := cond.eval(rt)
		if err != nil {
			return err
		}
		if kvJjTruthy(v) {
			return kvJjExecBody(rt, n.bodies[i], sb)
		}
	}
	return kvJjExecBody(rt, n.els, sb)
}

func kvJjAssign(frame map[string]any, targets []string, v any, pos int) error {
	if len(targets) == 1 {
		frame[targets[0]] = v
		return nil
	}
	items, err := kvJjIter(v)
	if err != nil {
		return kvJjAt(pos, err)
	}
	if _, ok := v.(kvJjUndef); ok {
		return kvJjErrf(pos, "cannot unpack undefined value")
	}
	if len(items) != len(targets) {
		return kvJjErrf(pos, "cannot unpack %d values into %d targets", len(items), len(targets))
	}
	for i, t := range targets {
		frame[t] = items[i]
	}
	return nil
}

func (n *kvJjFor) exec(rt *kvJjRT, sb *strings.Builder) error {
	seq, err := n.seq.eval(rt)
	if err != nil {
		return err
	}
	all, err := kvJjIter(seq)
	if err != nil {
		return kvJjAt(n.pos, err)
	}
	items := all
	if n.filter != nil {
		items = nil
		for _, it := range all {
			frame := map[string]any{}
			if err := kvJjAssign(frame, n.targets, it, n.pos); err != nil {
				return err
			}
			rt.scopes = append(rt.scopes, frame)
			ok, err := n.filter.eval(rt)
			rt.scopes = rt.scopes[:len(rt.scopes)-1]
			if err != nil {
				return err
			}
			if kvJjTruthy(ok) {
				items = append(items, it)
			}
		}
	}
	for idx, item := range items {
		loop := kvJjNewDict()
		loop.set("index0", idx)
		loop.set("index", idx+1)
		loop.set("revindex", len(items)-idx)
		loop.set("revindex0", len(items)-idx-1)
		loop.set("first", idx == 0)
		loop.set("last", idx == len(items)-1)
		loop.set("length", len(items))
		loop.set("depth", 1)
		loop.set("depth0", 0)
		if idx > 0 {
			loop.set("previtem", items[idx-1])
		}
		if idx+1 < len(items) {
			loop.set("nextitem", items[idx+1])
		}
		frame := map[string]any{"loop": loop}
		if err := kvJjAssign(frame, n.targets, item, n.pos); err != nil {
			return err
		}
		rt.scopes = append(rt.scopes, frame)
		err := kvJjExecBody(rt, n.body, sb)
		rt.scopes = rt.scopes[:len(rt.scopes)-1]
		if errors.Is(err, kvJjContinueSig) {
			continue
		}
		if errors.Is(err, kvJjBreakSig) {
			break
		}
		if err != nil {
			return err
		}
	}
	if len(items) == 0 {
		return kvJjExecBody(rt, n.els, sb)
	}
	return nil
}

func (n *kvJjLoopCtl) exec(rt *kvJjRT, sb *strings.Builder) error {
	if n.brk {
		return kvJjBreakSig
	}
	return kvJjContinueSig
}

func (n *kvJjSet) exec(rt *kvJjRT, sb *strings.Builder) error {
	v, err := n.e.eval(rt)
	if err != nil {
		return err
	}
	if n.attr == "" {
		return kvJjAssign(rt.scopes[len(rt.scopes)-1], n.targets, v, n.pos)
	}
	cur, ok := rt.lookup(n.targets[0])
	if !ok {
		return kvJjErrf(n.pos, "set: %q is undefined", n.targets[0])
	}
	ns, ok := cur.(*kvJjNS)
	if !ok {
		return kvJjErrf(n.pos, "set: %q is not a namespace", n.targets[0])
	}
	ns.attrs[n.attr] = v
	return nil
}

func (n *kvJjSetBlock) exec(rt *kvJjRT, sb *strings.Builder) error {
	var inner strings.Builder
	if err := kvJjExecBody(rt, n.body, &inner); err != nil {
		return err
	}
	rt.set(n.name, inner.String())
	return nil
}

func (n *kvJjMacroDef) exec(rt *kvJjRT, sb *strings.Builder) error {
	rt.set(n.decl.name, &kvJjMacro{decl: n.decl})
	return nil
}

// call binds arguments and renders the macro body. The body sees the render
// context and the template's top-level variables as they are at call time,
// never the caller's loop or local variables.
func (m *kvJjMacro) call(rt *kvJjRT, a *kvJjArgs) (any, error) {
	d := m.decl
	if len(a.pos) > len(d.params) {
		return nil, kvJjErrf(d.pos, "macro %q takes not more than %d argument(s)", d.name, len(d.params))
	}
	if rt.depth >= kvJjMaxCallDepth {
		return nil, kvJjErrf(d.pos, "macro %q: recursion too deep", d.name)
	}
	frame := map[string]any{}
	for _, k := range a.kw {
		idx := -1
		for i, p := range d.params {
			if p == k.name {
				idx = i
			}
		}
		if idx < 0 {
			return nil, kvJjErrf(d.pos, "macro %q takes no keyword argument %q", d.name, k.name)
		}
		if idx < len(a.pos) {
			return nil, kvJjErrf(d.pos, "macro %q got multiple values for argument %q", d.name, k.name)
		}
	}
	sub := &kvJjRT{scopes: []map[string]any{rt.scopes[0], rt.scopes[1], rt.root, frame}, root: rt.root, depth: rt.depth + 1}
	for i, p := range d.params {
		if v, ok := a.arg(i, p, nil); ok {
			frame[p] = v
			continue
		}
		if d.defaults[i] != nil {
			v, err := d.defaults[i].eval(sub)
			if err != nil {
				return nil, err
			}
			frame[p] = v
			continue
		}
		frame[p] = kvJjUndef{name: p}
	}
	var sb strings.Builder
	if err := kvJjExecBody(sub, d.body, &sb); err != nil {
		return nil, err
	}
	return sb.String(), nil
}

// ---------------------------------------------------------------------------
// Evaluation.

func (e *kvJjLit) eval(rt *kvJjRT) (any, error) { return e.v, nil }

func (e *kvJjVar) eval(rt *kvJjRT) (any, error) {
	if v, ok := rt.lookup(e.name); ok {
		return v, nil
	}
	return kvJjUndef{name: e.name}, nil
}

func (e *kvJjBool) eval(rt *kvJjRT) (any, error) {
	l, err := e.l.eval(rt)
	if err != nil {
		return nil, err
	}
	// Jinja and/or return an operand, not a bool — short-circuit included.
	if e.op == "and" {
		if !kvJjTruthy(l) {
			return l, nil
		}
		return e.r.eval(rt)
	}
	if kvJjTruthy(l) {
		return l, nil
	}
	return e.r.eval(rt)
}

func (e *kvJjNot) eval(rt *kvJjRT) (any, error) {
	v, err := e.e.eval(rt)
	if err != nil {
		return nil, err
	}
	return !kvJjTruthy(v), nil
}

func (e *kvJjCmp) eval(rt *kvJjRT) (any, error) {
	l, err := e.l.eval(rt)
	if err != nil {
		return nil, err
	}
	r, err := e.r.eval(rt)
	if err != nil {
		return nil, err
	}
	switch e.op {
	case "==":
		return kvJjEqual(l, r), nil
	case "!=":
		return !kvJjEqual(l, r), nil
	case "in", "notin":
		in, err := kvJjContains(r, l)
		if err != nil {
			return nil, kvJjAt(e.pos, err)
		}
		return in == (e.op == "in"), nil
	}
	ok, err := kvJjOrder(e.op, l, r)
	return ok, kvJjAt(e.pos, err)
}

func (e *kvJjArith) eval(rt *kvJjRT) (any, error) {
	l, err := e.l.eval(rt)
	if err != nil {
		return nil, err
	}
	r, err := e.r.eval(rt)
	if err != nil {
		return nil, err
	}
	v, err := kvJjBinOp(e.op, l, r)
	return v, kvJjAt(e.pos, err)
}

func kvJjBinOp(op string, l, r any) (any, error) {
	if op == "~" {
		ls, err := kvJjToStr(l)
		if err != nil {
			return nil, err
		}
		rs, err := kvJjToStr(r)
		if err != nil {
			return nil, err
		}
		return ls + rs, nil
	}
	if _, u := l.(kvJjUndef); u {
		return nil, fmt.Errorf("%q is undefined", l.(kvJjUndef).name)
	}
	if _, u := r.(kvJjUndef); u {
		return nil, fmt.Errorf("%q is undefined", r.(kvJjUndef).name)
	}
	li, lnum := kvJjNum(l)
	ri, rnum := kvJjNum(r)
	if lnum && rnum {
		switch op {
		case "+":
			return li + ri, nil
		case "-":
			return li - ri, nil
		case "*":
			return li * ri, nil
		case "//", "%":
			if ri == 0 {
				return nil, fmt.Errorf("integer division or modulo by zero")
			}
			q, m := li/ri, li%ri
			if m != 0 && (m < 0) != (ri < 0) {
				q--
				m += ri
			}
			if op == "//" {
				return q, nil
			}
			return m, nil
		}
		return nil, fmt.Errorf("operator %q yields a float, which is unsupported", op)
	}
	_, lm := l.(kvJjMarkup)
	_, rm := r.(kvJjMarkup)
	switch op {
	case "+":
		if lm || rm {
			return nil, fmt.Errorf("+ on markup escapes its operand; unsupported")
		}
		if ls, ok := l.(string); ok {
			if rs, ok := r.(string); ok {
				return ls + rs, nil
			}
		}
		if la, ok := l.([]any); ok {
			if ra, ok := r.([]any); ok {
				return append(append([]any{}, la...), ra...), nil
			}
		}
		if la, ok := l.(kvJjTuple); ok {
			if ra, ok := r.(kvJjTuple); ok {
				return append(append(kvJjTuple{}, la...), ra...), nil
			}
		}
	case "*":
		seq, n := l, ri
		if lnum && !rnum {
			seq, n = r, li
		} else if !rnum {
			break
		}
		if lm || rm {
			return nil, fmt.Errorf("* on markup is unsupported")
		}
		if n < 0 {
			n = 0
		}
		if s, ok := seq.(string); ok {
			return strings.Repeat(s, n), nil
		}
		if la, ok := seq.([]any); ok {
			out := []any{}
			for i := 0; i < n; i++ {
				out = append(out, la...)
			}
			return out, nil
		}
	case "%":
		if _, ok := kvJjStr(l); ok {
			return nil, fmt.Errorf("printf-style string formatting is unsupported")
		}
	}
	return nil, fmt.Errorf("unsupported operand types for %s: %s and %s", op, kvJjTypeName(l), kvJjTypeName(r))
}

func (e *kvJjNeg) eval(rt *kvJjRT) (any, error) {
	v, err := e.e.eval(rt)
	if err != nil {
		return nil, err
	}
	i, ok := kvJjNum(v)
	if !ok {
		return nil, kvJjErrf(e.pos, "bad operand type for unary -: %s", kvJjTypeName(v))
	}
	return -i, nil
}

func (e *kvJjCond) eval(rt *kvJjRT) (any, error) {
	c, err := e.cond.eval(rt)
	if err != nil {
		return nil, err
	}
	if kvJjTruthy(c) {
		return e.a.eval(rt)
	}
	if e.b == nil {
		return kvJjUndef{name: "conditional"}, nil
	}
	return e.b.eval(rt)
}

func (e *kvJjSeqLit) eval(rt *kvJjRT) (any, error) {
	out := make([]any, len(e.items))
	for i, it := range e.items {
		v, err := it.eval(rt)
		if err != nil {
			return nil, err
		}
		out[i] = v
	}
	if e.tuple {
		return kvJjTuple(out), nil
	}
	return out, nil
}

func (e *kvJjDictLit) eval(rt *kvJjRT) (any, error) {
	d := kvJjNewDict()
	for i := range e.keys {
		k, err := e.keys[i].eval(rt)
		if err != nil {
			return nil, err
		}
		ks, ok := kvJjStr(k)
		if !ok {
			return nil, kvJjErrf(e.pos, "dict keys must be strings, got %s", kvJjTypeName(k))
		}
		v, err := e.vals[i].eval(rt)
		if err != nil {
			return nil, err
		}
		d.set(ks, v)
	}
	return d, nil
}

func (e *kvJjAttr) eval(rt *kvJjRT) (any, error) {
	obj, err := e.obj.eval(rt)
	if err != nil {
		return nil, err
	}
	v, err := kvJjGetAttr(obj, e.name)
	return v, kvJjAt(e.pos, err)
}

// kvJjGetAttr is Jinja's sandboxed getattr: a Python attribute first (a
// method becomes a bound method value), then the item of the same name,
// else Undefined. Only Undefined itself raises.
func kvJjGetAttr(obj any, name string) (any, error) {
	switch o := obj.(type) {
	case kvJjUndef:
		return nil, fmt.Errorf("%q is undefined", o.name)
	case *kvJjDict:
		if kvJjHasAttrName(kvJjDictAttrs, name) {
			return &kvJjBound{obj: o, name: name}, nil
		}
		if v, ok := o.get(name); ok {
			return v, nil
		}
		return kvJjUndef{name: name}, nil
	case *kvJjNS:
		if v, ok := o.attrs[name]; ok {
			return v, nil
		}
		return kvJjUndef{name: name}, nil
	case string, kvJjMarkup:
		if kvJjHasAttrName(kvJjStrAttrs, name) {
			return &kvJjBound{obj: o, name: name}, nil
		}
		return kvJjUndef{name: name}, nil
	case []any, kvJjTuple:
		if kvJjHasAttrName(kvJjListAttrs, name) {
			return &kvJjBound{obj: o, name: name}, nil
		}
		return kvJjUndef{name: name}, nil
	case nil:
		return kvJjUndef{name: name}, nil
	}
	return nil, fmt.Errorf("attribute %q of %s is unsupported", name, kvJjTypeName(obj))
}

// kvJjGetItem is Jinja's sandboxed getitem: obj[key], falling back to the
// attribute for a string key, else Undefined. Only Undefined itself raises.
func kvJjGetItem(obj, key any) (any, error) {
	if u, ok := obj.(kvJjUndef); ok {
		return nil, fmt.Errorf("%q is undefined", u.name)
	}
	switch k := key.(type) {
	case string, kvJjMarkup:
		ks, _ := kvJjStr(k)
		if d, ok := obj.(*kvJjDict); ok {
			if v, ok := d.get(ks); ok {
				return v, nil
			}
		}
		if _, ok := obj.(*kvJjNS); ok {
			return nil, fmt.Errorf("namespace subscript is unsupported")
		}
		return kvJjGetAttr(obj, ks)
	case int, bool:
		i, _ := kvJjNum(k)
		var items []any
		switch o := obj.(type) {
		case []any:
			items = o
		case kvJjTuple:
			items = o
		case string, kvJjMarkup:
			s, _ := kvJjStr(o)
			rs := []rune(s)
			if i < 0 {
				i += len(rs)
			}
			if i < 0 || i >= len(rs) {
				return kvJjUndef{name: "index"}, nil
			}
			return string(rs[i]), nil
		case *kvJjDict, nil:
			return kvJjUndef{name: "index"}, nil
		default:
			return nil, fmt.Errorf("cannot index %s", kvJjTypeName(obj))
		}
		if i < 0 {
			i += len(items)
		}
		if i < 0 || i >= len(items) {
			return kvJjUndef{name: "index"}, nil
		}
		return items[i], nil
	}
	return nil, fmt.Errorf("subscript of type %s is unsupported", kvJjTypeName(key))
}

func (e *kvJjIndex) eval(rt *kvJjRT) (any, error) {
	obj, err := e.obj.eval(rt)
	if err != nil {
		return nil, err
	}
	idx, err := e.idx.eval(rt)
	if err != nil {
		return nil, err
	}
	v, err := kvJjGetItem(obj, idx)
	return v, kvJjAt(e.pos, err)
}

func (e *kvJjSlice) eval(rt *kvJjRT) (any, error) {
	obj, err := e.obj.eval(rt)
	if err != nil {
		return nil, err
	}
	var items []any
	var runes []rune
	str, tuple := false, false
	switch o := obj.(type) {
	case []any:
		items = o
	case kvJjTuple:
		items, tuple = o, true
	case string, kvJjMarkup:
		s, _ := kvJjStr(o)
		runes, str = []rune(s), true
	case kvJjUndef:
		return nil, kvJjErrf(e.pos, "%q is undefined", o.name)
	case nil, int, bool, *kvJjDict:
		return kvJjUndef{name: "slice"}, nil
	default:
		return nil, kvJjErrf(e.pos, "cannot slice %s", kvJjTypeName(obj))
	}
	n := len(items)
	if str {
		n = len(runes)
	}
	evalPart := func(part kvJjExpr) (int, bool, error) {
		if part == nil {
			return 0, false, nil
		}
		v, err := part.eval(rt)
		if err != nil {
			return 0, false, err
		}
		if v == nil {
			return 0, false, nil
		}
		i, ok := kvJjNum(v)
		if !ok {
			return 0, false, kvJjErrf(e.pos, "slice bound of type %s", kvJjTypeName(v))
		}
		return i, true, nil
	}
	step, hasStep, err := evalPart(e.step)
	if err != nil {
		return nil, err
	}
	if !hasStep {
		step = 1
	}
	if step == 0 {
		return nil, kvJjErrf(e.pos, "slice step cannot be zero")
	}
	start, hasStart, err := evalPart(e.start)
	if err != nil {
		return nil, err
	}
	stop, hasStop, err := evalPart(e.stop)
	if err != nil {
		return nil, err
	}
	clamp := func(i, lo, hi int) int {
		if i < lo {
			return lo
		}
		if i > hi {
			return hi
		}
		return i
	}
	var idxs []int
	if step > 0 {
		if !hasStart {
			start = 0
		} else if start < 0 {
			start += n
		}
		if !hasStop {
			stop = n
		} else if stop < 0 {
			stop += n
		}
		start, stop = clamp(start, 0, n), clamp(stop, 0, n)
		for i := start; i < stop; i += step {
			idxs = append(idxs, i)
		}
	} else {
		if !hasStart {
			start = n - 1
		} else if start < 0 {
			start += n
		}
		if !hasStop {
			stop = -1
		} else {
			if stop < 0 {
				stop += n
			}
			stop = clamp(stop, -1, n-1)
		}
		start = clamp(start, -1, n-1)
		for i := start; i > stop; i += step {
			idxs = append(idxs, i)
		}
	}
	if str {
		out := make([]rune, len(idxs))
		for k, i := range idxs {
			out[k] = runes[i]
		}
		return string(out), nil
	}
	out := make([]any, len(idxs))
	for k, i := range idxs {
		out[k] = items[i]
	}
	if tuple {
		return kvJjTuple(out), nil
	}
	return out, nil
}

func (a *kvJjCallArgs) eval(rt *kvJjRT) (*kvJjArgs, error) {
	out := &kvJjArgs{}
	if a == nil {
		return out, nil
	}
	for _, e := range a.pos {
		v, err := e.eval(rt)
		if err != nil {
			return nil, err
		}
		out.pos = append(out.pos, v)
	}
	for i, e := range a.kwVals {
		v, err := e.eval(rt)
		if err != nil {
			return nil, err
		}
		out.kw = append(out.kw, kvJjKw{name: a.kw[i], val: v})
	}
	return out, nil
}

func (e *kvJjCall) eval(rt *kvJjRT) (any, error) {
	// obj.method(...) dispatches on the receiver directly.
	if at, ok := e.fn.(*kvJjAttr); ok {
		obj, err := at.obj.eval(rt)
		if err != nil {
			return nil, err
		}
		args, err := e.args.eval(rt)
		if err != nil {
			return nil, err
		}
		if ns, ok := obj.(*kvJjNS); ok {
			fn, _ := kvJjGetAttr(ns, at.name)
			return kvJjCallValue(rt, fn, args, e.pos)
		}
		v, err := kvJjCallMethod(obj, at.name, args)
		return v, kvJjAt(at.pos, err)
	}
	fn, err := e.fn.eval(rt)
	if err != nil {
		return nil, err
	}
	args, err := e.args.eval(rt)
	if err != nil {
		return nil, err
	}
	return kvJjCallValue(rt, fn, args, e.pos)
}

func kvJjCallValue(rt *kvJjRT, fn any, args *kvJjArgs, pos int) (any, error) {
	switch f := fn.(type) {
	case *kvJjMacro:
		return f.call(rt, args)
	case *kvJjBuiltin:
		v, err := f.fn(rt, args)
		return v, kvJjAt(pos, err)
	case *kvJjBound:
		v, err := kvJjCallMethod(f.obj, f.name, args)
		return v, kvJjAt(pos, err)
	case kvJjUndef:
		return nil, kvJjErrf(pos, "%q is undefined", f.name)
	}
	return nil, kvJjErrf(pos, "%s object is not callable", kvJjTypeName(fn))
}

func (e *kvJjFilter) eval(rt *kvJjRT) (any, error) {
	v, err := e.e.eval(rt)
	if err != nil {
		return nil, err
	}
	args, err := e.args.eval(rt)
	if err != nil {
		return nil, err
	}
	f := kvJjFilters[e.name]
	out, err := f(rt, v, args)
	return out, kvJjAt(e.pos, err)
}

func (e *kvJjTest) eval(rt *kvJjRT) (any, error) {
	v, err := e.e.eval(rt)
	if err != nil {
		return nil, err
	}
	args := make([]any, len(e.args))
	for i, a := range e.args {
		if args[i], err = a.eval(rt); err != nil {
			return nil, err
		}
	}
	res, err := kvJjRunTest(e.name, v, args)
	if err != nil {
		return nil, kvJjAt(e.pos, err)
	}
	if e.negate {
		res = !res
	}
	return res, nil
}
