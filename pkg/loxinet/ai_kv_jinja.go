/*
 * ai_kv_jinja.go — Jinja template executor for profile-pinned chat
 * templates.
 *
 * The KV-exact chat surface must render byte-identically to the engine's
 * apply_chat_template. Engines render with HF transformers' Jinja environment
 * (ImmutableSandboxedEnvironment, trim_blocks=True, lstrip_blocks=True,
 * keep_trailing_newline=False, the loopcontrols extension, a json.dumps-based
 * tojson, raise_exception and strftime_now globals), so this executor
 * implements those exact whitespace semantics plus the language the pinned
 * production templates use:
 *
 *   statements  if/elif/else, for (tuple targets, inline if-filter, else,
 *               loop.* incl. previtem/nextitem), set (name, namespace
 *               attribute, tuple, block set), macro + call, continue, break
 *   expressions literals (str with Python escapes, int, bool, none, list,
 *               tuple, dict), conditional a if c else b, and/or/not,
 *               comparisons, in / not in, + - * // % ~, attribute,
 *               subscript and slice, calls with keyword arguments,
 *               filters and tests with arguments
 *
 * Filters, tests, methods and globals live in ai_kv_jinja_builtin.go; the
 * value model and the Python text conversions in ai_kv_jinja_value.go.
 *
 * Anything outside the subset fails loudly: unknown constructs are compile
 * errors, unknown filters/tests/methods and type mismatches are render
 * errors. A render error on a strict rule surfaces as a runtime fault (the
 * caller's contract), never as silently different bytes. Parity is proven
 * two ways: per construct against the rows of
 * cicd/common/kv_hash/fixtures/kv_jinja_construct_parity.json, and per model
 * against the whole-template goldens of kv_chat_render_parity.json — both
 * generated by the HF renderer itself, never by this executor.
 */

package loxinet

